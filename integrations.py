# 2. GitHub Issue Spec Publisher (PyGithub)
# =======================================================
class GitHubSpecPublisher:
    def __init__(self, token: Optional[str] = None, repo_name: Optional[str] = None):
        self.token = token or os.getenv("GITHUB_TOKEN")
        self.repo_name = repo_name or os.getenv("GITHUB_REPOSITORY")
        self._gh = None
        self._repo = None

    @property
    def repo(self):
        if self._repo is None:
            if not self.token or not self.repo_name:
                raise ValueError("GITHUB_TOKEN and GITHUB_REPOSITORY are required for GitHub publishing.")
            from github import Github
            self._gh = Github(self.token)
            self._repo = self._gh.get_repo(self.repo_name)
        return self._repo

    def format_markdown_issue(
        self,
        spec: Dict[str, Any],
        frame_url_map: Dict[str, str],
        execution_id: str
    ) -> str:
        """
        Generates a rich, professional Markdown issue specification.
        """
        md_lines = []
        md_lines.append(f"# {spec.get('title', 'Automated Bug Report')}\n")
        md_lines.append(f"> **Severity:** `{spec.get('severity', 'Medium')}` | **Task ID:** `{execution_id}` | **Generated by:** `SnapToSpec Agent`\n")
        
        md_lines.append("## 📌 Summary")
        md_lines.append(spec.get("bug_summary", "No summary provided.") + "\n")

        md_lines.append("## 🔁 Steps to Reproduce")
        for step in spec.get("reproduction_steps", []):
            s_num = step.get("step_number", 1)
            action = step.get("action", "")
            expected = step.get("expected_result", "")
            actual = step.get("actual_result", "")
            md_lines.append(f"{s_num}. **Action:** {action}")
            if expected:
                md_lines.append(f"   - *Expected:* {expected}")
            if actual:
                md_lines.append(f"   - *Actual:* {actual}")
        md_lines.append("")

        md_lines.append("## 📸 Evidence & Frame Timeline")
        timestamps = spec.get("timestamps_of_interest", [])
        for idx, item in enumerate(timestamps):
            ts = item.get("timestamp_seconds", 0)
            label = item.get("label", f"Frame {idx+1}")
            desc = item.get("description", "")
            
            # Find matching frame URL if available
            matching_url = None
            for local_path, url in frame_url_map.items():
                if f"{int(ts)}s" in local_path or f"frame_{idx+1:02d}" in local_path:
                    matching_url = url
                    break

            md_lines.append(f"### ⏱️ Timestamp: `{ts:.1f}s` - **{label}**")
            md_lines.append(f"*{desc}*\n")
            if matching_url:
                md_lines.append(f"![{label}]({matching_url})\n")
            else:
                md_lines.append("*(Snapshot uploaded)*\n")

        md_lines.append("## 🤖 Auto-Generated Playwright Test Script")
        md_lines.append("```typescript")
        md_lines.append(spec.get("playwright_script", "// No script generated"))
        md_lines.append("```\n")

        md_lines.append("---")
        md_lines.append("*Automated bug specification generated by SnapToSpec pipeline powered by Gemini 3.5 & Google Cloud.*")

        return "\n".join(md_lines)

    def create_issue(
        self,
        spec: Dict[str, Any],
        frame_url_map: Dict[str, str],
        execution_id: str
    ) -> Dict[str, Any]:
        """
        Publishes the issue directly to GitHub repository.
        """
        title = spec.get("title", f"[SnapToSpec] Bug Spec {execution_id}")
        body = self.format_markdown_issue(spec, frame_url_map, execution_id)
        labels = spec.get("tags", ["bug", "automated-spec"])

        # If token is not provided (e.g. in sandbox/test mode), return formatted issue
        if not self.token or not self.repo_name:
            print("[!] GITHUB_TOKEN or GITHUB_REPOSITORY not configured. Returning preview payload.")
            return {
                "status": "dry_run",
                "title": title,
                "body": body,
                "labels": labels,
                "issue_url": "https://github.com/mock-repo/issues/1"
            }

        issue = self.repo.create_issue(
            title=title,
            body=body,
            labels=labels
        )
        print(f"[+] GitHub Issue created successfully: {issue.html_url}")
        return {
            "status": "created",
            "issue_number": issue.number,
            "issue_url": issue.html_url
        }


