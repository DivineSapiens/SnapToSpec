# 3. Google Cloud Firestore State Tracker
# =======================================================
class FirestoreStateTracker:
    def __init__(self, collection_name: str = "snaptospec_tasks"):
        self.collection_name = collection_name
        self._db = None

    @property
    def db(self):
        if self._db is None:
            from google.cloud import firestore
            self._db = firestore.Client()
        return self._db

    def update_task_state(
        self,
        task_id: str,
        status: str,
        metadata: Optional[Dict[str, Any]] = None
    ):
        """
        Persists pipeline state transitions: QUEUED -> PROCESSING -> ANALYZED -> COMPLETED / FAILED
        """
        data = {
            "task_id": task_id,
            "status": status,
            "updated_at": datetime.now(timezone.utc).isoformat(),
        }
        if metadata:
            data.update(metadata)

        try:
            doc_ref = self.db.collection(self.collection_name).document(task_id)
            doc_ref.set(data, merge=True)
            print(f"[+] Firestore state updated: Task `{task_id}` -> `{status}`")
        except Exception as e:
            print(f"[!] Firestore update warning for `{task_id}`: {e}")


# =======================================================
# 4. Orchestration Integration Coordinator
# =======================================================
def publish_pipeline_results(
    task_id: str,
    spec: Dict[str, Any],
    local_frames: List[str],
    gcs_bucket: Optional[str] = None
) -> Dict[str, Any]:
    """
    Coordinates GCS upload, GitHub issue creation, and Firestore final state recording.
    """
    state_tracker = FirestoreStateTracker()
    state_tracker.update_task_state(task_id, "PUBLISHING_ASSETS")

    # 1. Upload frames to GCS
    frame_url_map = {}
    try:
        uploader = GCSUploader(bucket_name=gcs_bucket)
        frame_url_map = uploader.upload_all_frames(local_frames, execution_id=task_id)
    except Exception as e:
        print(f"[!] GCS frame upload fallback: {e}")
        for idx, path in enumerate(local_frames):
            frame_url_map[path] = f"https://storage.googleapis.com/{gcs_bucket or 'snaptospec'}/frames/{task_id}/frame_{idx}.jpg"

    # 2. Publish to GitHub
    publisher = GitHubSpecPublisher()
    gh_result = publisher.create_issue(spec, frame_url_map, execution_id=task_id)

    # 3. Finalize Firestore state
    final_payload = {
        "status": "COMPLETED",
        "spec_title": spec.get("title"),
        "github_issue_url": gh_result.get("issue_url"),
        "total_frames": len(local_frames),
        "frame_urls": list(frame_url_map.values()),
    }
    state_tracker.update_task_state(task_id, "COMPLETED", final_payload)

    return {
        "task_id": task_id,
        "github_result": gh_result,
        "frame_urls": frame_url_map,
        "status": "COMPLETED"
    }
