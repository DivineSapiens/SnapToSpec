import os
import mimetypes
from datetime import datetime, timezone
from pathlib import Path
from typing import List, Dict, Any, Optional
from dotenv import load_dotenv

load_dotenv()


# =======================================================
# 1. Google Cloud Storage (GCS) Frame Uploader
# =======================================================
class GCSUploader:
    def __init__(self, bucket_name: Optional[str] = None):
        self.bucket_name = bucket_name or os.getenv("GCS_OUTPUT_BUCKET", "snaptospec-frames")
        self._client = None
        self._bucket = None

    @property
    def client(self):
        if self._client is None:
            from google.cloud import storage
            self._client = storage.Client()
        return self._client

    @property
    def bucket(self):
        if self._bucket is None:
            self._bucket = self.client.bucket(self.bucket_name)
        return self._bucket

    def upload_frame(self, local_path: str, remote_prefix: str = "frames") -> str:
        """
        Uploads a single image frame to GCS and returns its accessible public or GCS URI.
        """
        path_obj = Path(local_path)
        if not path_obj.exists():
            raise FileNotFoundError(f"Local frame not found: {local_path}")

        blob_name = f"{remote_prefix}/{datetime.now(timezone.utc).strftime('%Y%m%d')}/{path_obj.name}"
        blob = self.bucket.blob(blob_name)

        content_type, _ = mimetypes.guess_type(local_path)
        blob.upload_from_filename(local_path, content_type=content_type or "image/jpeg")

        # Option A: Public URL if bucket is public, or standard storage URI
        # Using standard Google Cloud Storage public media link format:
        public_url = f"https://storage.googleapis.com/{self.bucket_name}/{blob_name}"
        return public_url

    def upload_all_frames(self, local_paths: List[str], execution_id: str) -> Dict[str, str]:
        """
        Uploads a list of frames, mapping local path -> remote public URL.
        """
        url_map = {}
        for path in local_paths:
            url = self.upload_frame(path, remote_prefix=f"frames/{execution_id}")
            url_map[path] = url
        return url_map


